import java.io.FileWriter;
import java.io.IOException;
import java.util.Random;
import java.util.Arrays;
import java.util.List;
import javax.swing.JOptionPane;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;

public class Message {

    // --- Message Fields ---
    private long messageID;
    private int numMessagesSent;
    private String recipientCell;
    private String messageContent;
    private String messageHash;
    private String messageStatus; // Sent, Stored, Disregarded

    // Static counter for message tracking
    private static int totalMessagesSent = 0;

    // --- Constructor ---
    public Message(int numMessagesSent) {
        // Randomly generated ten-digit number for Unique Message ID
        this.messageID = generateRandomTenDigitID();
        // This value starts with a number, this number is incremented and autogenerated
        this.numMessagesSent = numMessagesSent;
        this.messageStatus = "Pending"; // Initial status
    }

    // --- Getters and Setters ---
    public long getMessageID() {
        return messageID;
    }

    public int getNumMessagesSent() {
        return numMessagesSent;
    }

    public String getRecipientCell() {
        return recipientCell;
    }

    public void setRecipientCell(String recipientCell) {
        this.recipientCell = recipientCell;
    }

    public String getMessageContent() {
        return messageContent;
    }

    public void setMessageContent(String messageContent) {
        this.messageContent = messageContent;
    }

    public String getMessageHash() {
        return messageHash;
    }

    public String getMessageStatus() {
        return messageStatus;
    }
    
    // --- Required Methods from Instructions ---

    // Unique Message ID for tracking is a randomly generated ten-digit number
    private long generateRandomTenDigitID() {
        Random rnd = new Random();
        // Generates a number between 1,000,000,000 and 9,999,999,999 (inclusive)
        long tenDigitMin = 1000000000L;
        long tenDigitMax = 9999999999L;
        return tenDigitMin + (long)(rnd.nextDouble() * (tenDigitMax - tenDigitMin + 1));
    }
    
    /**
     * This method ensures that the message ID is not more than ten characters.
     * (A ten-digit number is 10 characters long, so we check if it's <= 10)
     */
    public boolean checkMessageID() {
        return String.valueOf(this.messageID).length() <= 10;
    }

    /**
     * This method ensures that the recipient cell number is no more than ten characters long and 
     * contains an international code.
     * For simplicity, the check for an 'international code' is a simple check for a leading '+'.
     */
    public int checkRecipientCell() {
        if (recipientCell == null || recipientCell.isEmpty()) {
            return 0; // Empty
        }
        
        // Ensure it has no more than ten characters *after* the international code check
        if (recipientCell.length() > 10 && recipientCell.startsWith("+")) {
            // A 10-digit number plus a '+' sign (e.g., +27831234567) is 11 characters. 
            // The prompt states "no more than ten characters and contains an international code"
            // This is a contradiction, as an international code like +27 + 8 digits = 11 chars.
            // We'll interpret this as: the *digits* part should be around 10. For now, we'll enforce *total* length <= 10, 
            // but log a message if it contains an international code for demonstration.
            if (recipientCell.length() <= 10) {
                 return 1; // Valid
            }
        } else if (recipientCell.length() <= 10) {
             // Does not start with '+', but meets the 10 character length requirement
             return 1; // Valid
        }
        
        return -1; // Invalid
    }

    /**
     * Creates and returns the Message Hash
     * Hash format: first two digits of message ID : num messages sent : first word and last word of message
     */
    public String createMessageHash() {
        if (messageContent == null || messageContent.trim().isEmpty()) {
            return "HASH_ERROR:EMPTY_MESSAGE";
        }
        
        // 1. First two numbers of the message ID
        String idPrefix = String.valueOf(messageID).substring(0, 2);

        // 2. The number of the message (numMessagesSent)
        String messageNum = String.valueOf(numMessagesSent);

        // 3. First and last words in the message
        String[] words = messageContent.trim().replaceAll("[^a-zA-Z0-9 ]", "").split("\\s+");
        String firstWord = words.length > 0 ? words[0] : "";
        String lastWord = words.length > 1 ? words[words.length - 1] : firstWord;

        // Combine and convert to all caps
        this.messageHash = (idPrefix + ":" + messageNum + ":" + firstWord + lastWord).toUpperCase();
        return this.messageHash;
    }

    /**
     * Allows the user to choose if they want to send, store, or disregard the message
     * Returns the chosen status string.
     */
    public String SentMessage() {
        String[] options = {"Send Message", "Disregard Message", "Store Message to send later"};
        int choice = JOptionPane.showOptionDialog(
            null,
            "Choose an action for the message:",
            "Message Action",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE,
            null,
            options,
            options[0] // Default option
        );

        switch (choice) {
            case 0: // Send Message
                this.messageStatus = "Sent";
                totalMessagesSent++; // Increment total messages sent
                return "Sent";
            case 1: // Disregard Message
                this.messageStatus = "Disregarded";
                return "Disregarded";
            case 2: // Store Message to send later
                // The actual storing to JSON happens in the storeMessage() method
                this.messageStatus = "Stored";
                return "Stored";
            default:
                this.messageStatus = "Disregarded"; // Treat close/escape as disregarded
                return "Disregarded";
        }
    }

    /**
     * Returns a list of all the messages sent while the program is running.
     * (Since this method is on the Message object, it will return the details of *this* message instance.)
     */
    public String printMessages() {
        return "Message ID: " + messageID + 
               "\nMessage Hash: " + messageHash +
               "\nRecipient: " + recipientCell +
               "\nMessage: " + messageContent +
               "\nStatus: " + messageStatus +
               "\n---";
    }

    /**
     * This method returns the total number of messages sent
     */
    public static int returnTotalMessages() {
        return totalMessagesSent;
    }
    
    /**
     * Creates a method to store the message details in a JSON file.
     * Uses the Gson library for easy serialization.
     */
    public void storeMessage() {
        // Use GsonBuilder to format the JSON nicely (pretty printing)
        Gson gson = new GsonBuilder().setPrettyPrinting().create();
        String jsonFileName = "message_" + this.messageID + ".json";
        
        try (FileWriter writer = new FileWriter(jsonFileName)) {
            // Serialize the current Message object to JSON
            gson.toJson(this, writer);
            JOptionPane.showMessageDialog(null, "Message stored successfully in " + jsonFileName, "Storage Successful", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(null, "Error storing message to JSON: " + e.getMessage(), "Storage Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    // --- Helper Method for Displaying Final Details ---
    public String getDisplayDetails() {
        return "Message Details (Status: " + this.messageStatus + "):" +
               "\n\nMessageID: " + this.messageID +
               "\nMessage Hash: " + this.messageHash +
               "\nRecipient: " + this.recipientCell +
               "\nMessage: " + this.messageContent;
    }
}